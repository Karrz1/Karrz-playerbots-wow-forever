# Writes the vanilla (VMaNGOS 1.12) creature numbers for sql/custom/world from the extract of the VMaNGOS dump (extract-vmangos.ps1,
# or the whole dump through VMANGOS_SRC), using the creature_template row of the highest patch <= 10 (compare_creatures.load_vanilla):
#   python3 -I gen_creature_stats.py > ../../sql/custom/world/2026_10_11_00_world_classic_creature_vanilla.sql
# creature_classic_level: fixed levels of every creature (health, mana and armor are advocaite's creature_classic_stats multipliers);
# creature_template_resistance: vanilla resistances. Every statement is safe to run again.
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import compare_creatures as c

SRC = os.environ.get('VMANGOS_SRC') or os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'vmangos_extract.sql.gz')
SCHOOLS = (('holy_res', 1), ('fire_res', 2), ('nature_res', 3), ('frost_res', 4), ('shadow_res', 5), ('arcane_res', 6))


def esc(n):
    return n.replace("\\'", "'").replace("'", "''")[:60]


def main():
    v = c.load_vanilla(SRC)
    entries = sorted(e for e, r in v.items() if r.get('level_min') is not None and r.get('health_min') is not None)
    out = []
    out.append('-- Classic 1.60: vanilla (VMaNGOS 1.12, world_full_14_june_2021, highest patch row <= 10) creature levels and resistances.')
    out.append("-- Health, mana and armor come from advocaite's creature_classic_stats / creature_classic_classlevelstats (2026_10_11_11), same VMaNGOS source.")
    out.append('-- Generated by tools/classic_spell_values/gen_creature_stats.py. Safe to run again.')

    def chunks(rows, head, tail=';'):
        for i in range(0, len(rows), 500):
            out.append(head)
            out.append(',\n'.join(rows[i:i + 500]) + tail)

    level_rows, res_rows = [], []
    for e in entries:
        r = v[e]
        lmin, lmax = int(r['level_min']), int(r['level_max'])
        i = lambda k: int(r.get(k) or 0)
        level_rows.append('(%d,%d,%d)' % (e, max(lmin, 1), max(lmax, lmin, 1)))
        for col, school in SCHOOLS:
            if i(col):
                res_rows.append('(%d,%d,%d)' % (e, school, i(col)))
    chunks(level_rows, 'REPLACE INTO `creature_classic_level` (`entry`,`level_min`,`level_max`) VALUES')
    out.append('DELETE FROM `creature_template_resistance` WHERE `CreatureID` IN (SELECT `entry` FROM `creature_classic_level`);')
    chunks(res_rows, 'INSERT INTO `creature_template_resistance` (`CreatureID`,`School`,`Resistance`) VALUES')
    sys.stdout.write('\n'.join(out) + '\n')
    sys.stderr.write('creatures: %d, resistance rows: %d\n' % (len(level_rows), len(res_rows)))


main()
