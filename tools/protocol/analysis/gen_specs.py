"""Turns main-group-cases.txt (the field sequence of every message the 70291 client reads, see README.md) into the table the golden
byte tests use: tests/game/data/Classic70291MainGroupSpecs.inc.

usage: gen_specs.py MAIN_GROUP_CASES.txt OUT.inc

Per case index the table holds one of
  "u32 u8 GUID"  the flat field sequence (u8 u16 u32 u64 GUID), loops appear once: a probe packet must hold one element per container
  "?"            a field the analysis could not resolve (nested reader or container helper): to decode
  "!"            the reader page was not decrypted in the dump: to decode (needs a longer dump)
Only field layout facts are stored, no client code.
"""
import sys

rows = [line.rstrip("\n").split("\t") for line in open(sys.argv[1], encoding="utf-8") if line.strip()]
out = ["// Generated by tools/protocol/analysis/gen_specs.py from the 70291 client's message readers. Do not edit by hand.",
       "// { main group case index (opcode 0x470000 + index), spec } - see the generator for the spec grammar."]
for r in rows:
    index = int(r[0], 16)
    spec = r[-1]
    if "(ctor page not decrypted)" in spec:
        spec = "!"
    elif spec == "(no fields)":
        spec = ""
    elif "?" in spec.split():
        spec = "?"
    out.append('{ 0x%03X, "%s" },' % (index, spec))
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(rows), "cases")
