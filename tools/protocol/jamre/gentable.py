"""Generate ClassicServerOpcodes70291.inc from alignment maps (old-build index -> new-build index per message group)."""
from __future__ import annotations

import json
import sys

from .legacy import legacy_70245, load_core, load_overrides


def generate(core: dict[str, int], overrides: dict[str, int], group_maps: dict[int, dict]) -> tuple[list[tuple[str, int, str]], list[str]]:
    """group_maps: old wire group -> {"new_group": int, "map": {old index: new index}}.

    Returns (entries (name, wire70291, source), unresolved names).
    """
    entries, unresolved = [], []
    for name, value in sorted(core.items(), key=lambda kv: kv[1]):
        old = legacy_70245(name, value, overrides)
        g, i = old >> 16, old & 0xFFFF
        gm = group_maps.get(g)
        if gm is None:
            unresolved.append(f"{name} (group {g:#x} not aligned)")
            continue
        new_i = gm["map"].get(i)
        if new_i is None:
            unresolved.append(f"{name} (index {g:#x}:{i:#x} in an inserted/changed block)")
            continue
        entries.append((name, (gm["new_group"] << 16) | new_i, f"{g:#x}:{i:#x}"))
    return entries, unresolved


def render(entries) -> str:
    lines = ["// Generated by tools/protocol/jamre/gentable.py from the client dispatch alignment. Do not edit by hand.",
             "// {core opcode, 70291 wire opcode}, comment = 70245 wire group:index it was aligned from"]
    for name, wire, src in entries:
        lines.append(f"    {{ {name}, 0x{wire:06X} }}, // {src}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    import argparse

    p = argparse.ArgumentParser()
    p.add_argument("opcodes_h"); p.add_argument("classic_opcodes_cpp"); p.add_argument("maps_json"); p.add_argument("out_inc")
    a = p.parse_args(argv)
    maps = {int(k, 0): {"new_group": int(v["new_group"], 0) if isinstance(v["new_group"], str) else v["new_group"],
                        "map": {int(i): int(j) for i, j in v["map"].items()}} for k, v in json.load(open(a.maps_json)).items()}
    entries, unresolved = generate(load_core(a.opcodes_h), load_overrides(a.classic_opcodes_cpp), maps)
    open(a.out_inc, "w", encoding="latin-1").write(render(entries))
    for u in unresolved:
        print("UNRESOLVED", u, file=sys.stderr)
    print(f"{len(entries)} entries, {len(unresolved)} unresolved", file=sys.stderr)


if __name__ == "__main__":
    main()
